  t(key) {
    const loc = this.currentLocale;
    return this.translations[loc]?.[key] || this.translations['en']?.[key] || key;
  },

  setLocale(lang) {
    if (lang !== 'en' && lang !== 'ar') return;
    this.currentLocale = lang;
    localStorage.setItem('sadat_lang', lang);
    document.documentElement.lang = lang;
    document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
    if (window.renderApp) {
      window.renderApp();
    }
  },

  init() {
    const saved = localStorage.getItem('sadat_lang') || 'en';
    this.setLocale(saved);
  }
